//! Alternative Services (Alt-Svc) cache — RFC 7838.
//!
//! This module is a memory-safe Rust rewrite of the curl 8.x source-of-truth
//! `lib/altsvc.c`. It maintains the *Alternative Services* cache described in
//! [RFC 7838](https://datatracker.ietf.org/doc/html/rfc7838), which lets curl
//! transparently switch a request from an origin (`h1`/`h2`/`h3` + host + port)
//! to an advertised alternate endpoint — most commonly to hop from HTTP/1.1 or
//! HTTP/2 to an HTTP/3 (QUIC) service on a different port.
//!
//! The cache has three responsibilities, each a faithful port of its C
//! counterpart:
//!
//! * **Header ingestion** — [`AltSvc::parse`] consumes an `Alt-Svc:` response
//!   header value (`h2=":443"`, `h3=":443"; ma=3600; persist=1`, `clear`, …),
//!   applying RFC 7838 update / replace / clear semantics.
//! * **Persistence** — [`AltSvc::save`] / [`AltSvc::load`] write and read the
//!   on-disk cache in curl's exact, **byte-compatible** nine-field line format
//!   (IPv6 hosts written bracketed), so a file produced by this implementation
//!   round-trips identically against a curl 8.x reference binary.
//! * **Lookup** — [`AltSvc::lookup`] is the query the connection layer uses to
//!   pick an alternative service for a given origin, honoring the
//!   `CURLALTSVC_H*` version bitmask and dropping expired entries.
//!
//! # Parity notes
//!
//! * Entry insertion order is preserved (curl uses an ordered linked list;
//!   this module uses a [`Vec`]). The save format emits entries in that order.
//! * Expired entries are **loaded and saved** unchanged; expiry is only
//!   consulted — and expired entries pruned — during [`AltSvc::lookup`],
//!   exactly as in `lib/altsvc.c`.
//! * The [`AlpnId`] discriminants are intentionally equal to the
//!   `CURLALTSVC_H*` flag bits, mirroring `enum alpnid` in `lib/hostip.h`; this
//!   is what lets the lookup version filter be a direct bitwise `&`.
//!
//! # Safety
//!
//! This module is implemented entirely in safe Rust, honoring the
//! workspace-wide policy that confines low-level memory operations to the FFI
//! crate. It performs no raw-pointer, transmute, or FFI operations.

use std::fs;
use std::net::Ipv6Addr;

use chrono::{DateTime, Datelike, NaiveDate, Timelike, Utc};

use crate::error::{Error, Result};

// ---------------------------------------------------------------------------
// Public bitmask constants — mirror `include/curl/curl.h`.
//
// These are the bits accepted by the `CURLOPT_ALTSVC_CTRL` option. Their
// integer values are a frozen part of the public contract and must match curl
// 8.x exactly. They are declared as `i64` because the underlying libcurl option
// is a C `long`.
// ---------------------------------------------------------------------------

/// `CURLALTSVC_READONLYFILE` — do not write the cache file back out on save.
pub const CURLALTSVC_READONLYFILE: i64 = 1 << 2;
/// `CURLALTSVC_H1` — allow selecting an HTTP/1.1 alternative.
pub const CURLALTSVC_H1: i64 = 1 << 3;
/// `CURLALTSVC_H2` — allow selecting an HTTP/2 alternative.
pub const CURLALTSVC_H2: i64 = 1 << 4;
/// `CURLALTSVC_H3` — allow selecting an HTTP/3 alternative.
pub const CURLALTSVC_H3: i64 = 1 << 5;

// ---------------------------------------------------------------------------
// Internal parser limits — mirror the `#define`s at the top of `lib/altsvc.c`
// (and `MAX_IPADR_LEN` from `lib/urldata.h`).
// ---------------------------------------------------------------------------

/// Maximum length of a single line read from the cache file (`MAX_ALTSVC_LINE`).
const MAX_ALTSVC_LINE: usize = 4095;
/// Maximum length of the quoted date field (`MAX_ALTSVC_DATELEN`), e.g.
/// `20191231 00:00:00` which is exactly 17 bytes.
const MAX_ALTSVC_DATELEN: usize = 17;
/// Maximum length of a host token (`MAX_ALTSVC_HOSTLEN`).
const MAX_ALTSVC_HOSTLEN: usize = 2048;
/// Maximum length of an ALPN token (`MAX_ALTSVC_ALPNLEN`).
const MAX_ALTSVC_ALPNLEN: usize = 10;
/// Maximum length of a textual IP address (`MAX_IPADR_LEN`), sized for
/// `ffff:ffff:ffff:ffff:ffff:ffff:255.255.255.255` plus its terminator.
const MAX_IPADR_LEN: usize = 46;

/// The largest value representable by a 64-bit signed `time_t`, matching
/// curl's `TIME_T_MAX` on the supported 64-bit platforms. Used to cap the
/// `ma` (max-age) computation exactly as `lib/altsvc.c` does.
const TIME_T_MAX: i64 = i64::MAX;

/// The two header lines written verbatim at the top of every saved cache file.
/// Reproduced byte-for-byte from `Curl_altsvc_save` in `lib/altsvc.c`.
const ALTSVC_FILE_HEADER: &str = "# Your alt-svc cache. https://curl.se/docs/alt-svc.html\n\
     # This file was generated by libcurl! Edit at your own risk.\n";

// ---------------------------------------------------------------------------
// ALPN identifiers
// ---------------------------------------------------------------------------

/// Application-Layer Protocol Negotiation identifier for an alternative
/// service, mirroring the C `enum alpnid` in `lib/hostip.h`.
///
/// The discriminants are **deliberately** equal to the `CURLALTSVC_H*` flag
/// bits ([`CURLALTSVC_H1`] = 8, [`CURLALTSVC_H2`] = 16, [`CURLALTSVC_H3`] = 32).
/// This equivalence is relied upon by [`AltSvc::lookup`], which tests the
/// caller-supplied version bitmask against a destination id with a plain
/// bitwise `&` — precisely as curl does with `versions & (int)as->dst.alpnid`.
#[repr(i32)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum AlpnId {
    /// `ALPN_none` — unknown / unset (also the "rubbish input" sentinel).
    None = 0,
    /// `ALPN_h1` — HTTP/1.1 (`h1`, or the ALPN token `http/1.1`).
    H1 = 1 << 3,
    /// `ALPN_h2` — HTTP/2 (`h2`).
    H2 = 1 << 4,
    /// `ALPN_h3` — HTTP/3 (`h3`).
    H3 = 1 << 5,
}

impl AlpnId {
    /// Returns the integer bit value of this id (`self as i32`).
    ///
    /// Because the discriminants equal the `CURLALTSVC_H*` bits, this value can
    /// be tested directly against a `CURLALTSVC_H*` version mask.
    #[must_use]
    pub const fn bits(self) -> i32 {
        self as i32
    }

    /// Maps an ALPN token to its id, mirroring `Curl_alpn2alpnid`
    /// (`lib/connect.c`).
    ///
    /// The comparison is **case-sensitive** (curl uses `memcmp`): the two-byte
    /// tokens `h1`, `h2`, `h3` map to the corresponding protocol, the eight-byte
    /// token `http/1.1` maps to [`AlpnId::H1`], and anything else — including
    /// differently-cased spellings — maps to [`AlpnId::None`].
    #[must_use]
    pub fn from_alpn(name: &str) -> AlpnId {
        match name.as_bytes() {
            b"h1" => AlpnId::H1,
            b"h2" => AlpnId::H2,
            b"h3" => AlpnId::H3,
            b"http/1.1" => AlpnId::H1,
            _ => AlpnId::None,
        }
    }

    /// Returns the canonical textual name for this id, mirroring
    /// `Curl_alpnid2str` (`lib/altsvc.c`). [`AlpnId::None`] renders as the empty
    /// string, exactly as curl's `default` branch does.
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            AlpnId::H1 => "h1",
            AlpnId::H2 => "h2",
            AlpnId::H3 => "h3",
            AlpnId::None => "",
        }
    }
}

// ---------------------------------------------------------------------------
// Cache entry types
// ---------------------------------------------------------------------------

/// One side (source *or* destination) of an alternative-service mapping,
/// mirroring the C `struct althost` in `lib/altsvc.h`.
///
/// `host` is stored **without** surrounding brackets even for IPv6 literals;
/// the brackets are re-applied on save (see [`AltSvc::save`]).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AltHost {
    /// The host name or IP literal (IPv6 stored unbracketed).
    pub host: String,
    /// The TCP/UDP port.
    pub port: u16,
    /// The ALPN protocol identifier for this endpoint.
    pub alpnid: AlpnId,
}

/// A single cached alternative service, mirroring the C `struct altsvc`
/// (`lib/altsvc.h`): a source origin, its advertised destination, an absolute
/// expiry, and the RFC 7838 `persist` / `prio` attributes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AltSvcEntry {
    /// The origin this alternative applies to.
    pub src: AltHost,
    /// The advertised alternative endpoint.
    pub dst: AltHost,
    /// Absolute expiry as a Unix timestamp (seconds, UTC). Matches curl's
    /// `time_t expires`.
    pub expires: i64,
    /// Whether the entry should persist across cache reloads (`persist=1`).
    pub persist: bool,
    /// RFC 7838 priority. curl currently always stores `0` here; preserved for
    /// format compatibility.
    pub prio: u32,
}

/// The result of a successful [`AltSvc::lookup`]: the chosen destination
/// endpoint plus whether it is effectively identical to the origin.
///
/// This is an owned value (rather than a borrow of the cache) so callers in the
/// connection layer can hold onto the selected alternative without pinning a
/// borrow of the whole cache.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AltSvcMatch {
    /// The destination ALPN protocol to switch to.
    pub alpnid: AlpnId,
    /// The destination host (IPv6 unbracketed).
    pub host: String,
    /// The destination port.
    pub port: u16,
    /// `true` when the destination host and port are the same as the queried
    /// origin (curl's `psame_destination`), i.e. only the protocol differs.
    pub same_destination: bool,
}

// ---------------------------------------------------------------------------
// The cache
// ---------------------------------------------------------------------------

/// The Alt-Svc cache, mirroring the C `struct altsvcinfo` (`lib/altsvc.h`).
///
/// Holds the ordered set of [`AltSvcEntry`] values, the optional backing file
/// name (remembered across a [`load`](AltSvc::load) so a later
/// [`save`](AltSvc::save) can default to it), and the publicly settable
/// `CURLALTSVC_*` flag bitmask.
#[derive(Debug, Clone)]
pub struct AltSvc {
    /// The cache file name remembered from the most recent [`load`](AltSvc::load).
    filename: Option<String>,
    /// The cached entries, in insertion order (curl's linked list order).
    entries: Vec<AltSvcEntry>,
    /// The `CURLALTSVC_*` control bitmask (a C `long`).
    flags: i64,
}

impl Default for AltSvc {
    fn default() -> Self {
        Self::new()
    }
}

impl AltSvc {
    /// Creates a new, empty Alt-Svc cache, mirroring `Curl_altsvc_init`.
    ///
    /// The default control mask enables all three protocol versions
    /// (`CURLALTSVC_H1 | CURLALTSVC_H2 | CURLALTSVC_H3`). This matches a curl
    /// build with HTTP/2 and HTTP/3 support compiled in — which is always the
    /// case for this Rust rewrite (both `h2` and `h3` are first-class).
    #[must_use]
    pub fn new() -> Self {
        AltSvc {
            filename: None,
            entries: Vec::new(),
            flags: CURLALTSVC_H1 | CURLALTSVC_H2 | CURLALTSVC_H3,
        }
    }

    /// Returns the number of entries currently cached (curl's
    /// `Curl_llist_count`).
    #[must_use]
    pub fn len(&self) -> usize {
        self.entries.len()
    }

    /// Returns `true` when the cache holds no entries.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    /// Returns a read-only view of the cached entries in insertion order.
    #[must_use]
    pub fn entries(&self) -> &[AltSvcEntry] {
        &self.entries
    }

    /// Returns the current `CURLALTSVC_*` control bitmask.
    #[must_use]
    pub fn flags(&self) -> i64 {
        self.flags
    }

    /// Overwrites the `CURLALTSVC_*` control bitmask.
    ///
    /// Prefer [`ctrl`](AltSvc::ctrl) when reproducing the `CURLOPT_ALTSVC_CTRL`
    /// semantics (which reject a zero mask).
    pub fn set_flags(&mut self, flags: i64) {
        self.flags = flags;
    }

    /// Returns the remembered cache file name, if any.
    #[must_use]
    pub fn filename(&self) -> Option<&str> {
        self.filename.as_deref()
    }
}

impl AltSvc {
    /// Applies an external `CURLALTSVC_*` control bitmask, mirroring
    /// `Curl_altsvc_ctrl`.
    ///
    /// A zero mask is rejected with `CURLE_BAD_FUNCTION_ARGUMENT`
    /// ([`Error::BadFunctionArgument`]); any other value replaces the current
    /// flags wholesale.
    ///
    /// # Errors
    ///
    /// Returns [`Error::BadFunctionArgument`] when `ctrl` is `0`.
    pub fn ctrl(&mut self, ctrl: i64) -> Result<()> {
        if ctrl == 0 {
            return Err(Error::bad_argument(
                "CURLALTSVC_CTRL requires a non-zero bitmask",
            ));
        }
        self.flags = ctrl;
        Ok(())
    }

    /// Loads Alt-Svc entries from `file`, mirroring `Curl_altsvc_load`.
    ///
    /// The file name is remembered (so a later [`save`](AltSvc::save) with no
    /// explicit path defaults to it) **before** the file is opened, exactly as
    /// curl does. A missing or unreadable file is **not** an error — it simply
    /// yields no entries, matching curl's behavior of only returning errors on
    /// problems that prevent alt-svc handling entirely.
    ///
    /// Each line is parsed independently; a malformed line is skipped without
    /// aborting the load. Comment lines (first non-blank byte `#`) are ignored.
    /// Expired entries are loaded unchanged — expiry is only consulted during
    /// [`lookup`](AltSvc::lookup).
    ///
    /// # Errors
    ///
    /// This function does not currently return an error; the [`Result`] shape is
    /// retained for API parity with the C `CURLcode` contract and for forward
    /// compatibility.
    pub fn load(&mut self, file: &str) -> Result<()> {
        // Keep a private copy of the file name so it survives an easy-handle
        // reset (parity: curl stores it even when the subsequent open fails).
        self.filename = Some(file.to_string());

        // A missing / unreadable file is not an error: no entries are loaded.
        let bytes = match fs::read(file) {
            Ok(b) => b,
            Err(_) => return Ok(()),
        };
        // Alt-Svc cache files are ASCII; lossy decoding cannot corrupt valid
        // input and guarantees we never fail on stray bytes.
        let content = String::from_utf8_lossy(&bytes);

        for segment in content.split('\n') {
            // Parity: Curl_get_line aborts the load on an over-long line.
            if segment.len() > MAX_ALTSVC_LINE {
                break;
            }
            let mut cur = Parser::new(segment);
            cur.pass_blanks();
            // Comment lines start with '#'; everything else is a candidate.
            if cur.first() == Some(b'#') {
                continue;
            }
            if let Some(entry) = parse_file_line(cur.remaining()) {
                self.entries.push(entry);
            }
        }
        Ok(())
    }

    /// Writes the cache to disk in curl's byte-compatible format, mirroring
    /// `Curl_altsvc_save`.
    ///
    /// The target path is `file` when supplied, otherwise the name remembered
    /// from the most recent [`load`](AltSvc::load). Nothing is written — and
    /// `Ok(())` is returned — when the [`CURLALTSVC_READONLYFILE`] flag is set,
    /// or when no (or an empty) path is available.
    ///
    /// Every entry is written, in insertion order, including expired ones. IPv6
    /// literal hosts are emitted bracketed. The write is performed to a sibling
    /// temporary file which is then atomically renamed over the target,
    /// mirroring curl's `Curl_fopen` + rename strategy.
    ///
    /// # Errors
    ///
    /// * [`Error::Io`] if the temporary file cannot be written.
    /// * [`Error::Write`] if the atomic rename over the target fails
    ///   (`CURLE_WRITE_ERROR`).
    /// * [`Error::BadFunctionArgument`] if an entry's expiry cannot be
    ///   represented as a calendar date (mirrors a `curlx_gmtime` failure).
    pub fn save(&self, file: Option<&str>) -> Result<()> {
        // Resolve the target: an explicit argument wins, else the stored name.
        let resolved = match file {
            Some(f) => Some(f),
            None => self.filename.as_deref(),
        };
        // Read-only caches are never written back (checked before the
        // empty-path test, exactly as curl orders it).
        if self.flags & CURLALTSVC_READONLYFILE != 0 {
            return Ok(());
        }
        let path = match resolved {
            Some(f) if !f.is_empty() => f,
            _ => return Ok(()), // no file or zero-length name: nothing to do
        };

        let mut out = String::from(ALTSVC_FILE_HEADER);
        for entry in &self.entries {
            out.push_str(&entry_to_line(entry)?);
        }

        // Atomic replace: write to a uniquely-named sibling, then rename.
        let tmp = format!("{path}.tmp.{}", std::process::id());
        fs::write(&tmp, out.as_bytes())?;
        if fs::rename(&tmp, path).is_err() {
            let _ = fs::remove_file(&tmp);
            return Err(Error::Write);
        }
        Ok(())
    }
}

impl AltSvc {
    /// Removes every cached entry whose **source** origin matches
    /// `(srcalpnid, srchost, srcport)`, mirroring `altsvc_flush`.
    ///
    /// Host comparison ignores a single trailing dot on `srchost` and is
    /// case-insensitive (see [`hostcompare`]).
    fn flush(&mut self, srcalpnid: AlpnId, srchost: &str, srcport: u16) {
        self.entries.retain(|e| {
            !(e.src.alpnid == srcalpnid
                && e.src.port == srcport
                && hostcompare(srchost, &e.src.host))
        });
    }

    /// Ingests an `Alt-Svc:` response-header value, mirroring
    /// `Curl_altsvc_parse`.
    ///
    /// `value` is the header content to the right of the `Alt-Svc:` name.
    /// `srcalpnid` / `srchost` / `srcport` identify the origin the header was
    /// received over. RFC 7838 semantics are applied:
    ///
    /// * The magic keyword `clear` flushes every alternative for the origin.
    /// * The first advertised alternative on a line replaces the origin's
    ///   previously cached set (subsequent alternatives on the same line are
    ///   appended).
    /// * The optional `ma` (max-age, seconds) and `persist=1` parameters are
    ///   honored; unknown parameters are skipped. A missing `ma` defaults to
    ///   24 hours.
    /// * Alternatives with an unparseable host, an out-of-range port, an
    ///   unknown protocol token, or a missing quote are rejected individually
    ///   without failing the whole header.
    ///
    /// Invalid data is rejected silently (no error), matching curl. Diagnostic
    /// messages mirror curl's `infof` output and are emitted via `tracing` to
    /// preserve the `--verbose` vocabulary.
    ///
    /// # Errors
    ///
    /// This function does not currently return an error; the [`Result`] shape is
    /// retained for API parity with the C `CURLcode` contract.
    pub fn parse(
        &mut self,
        value: &str,
        srcalpnid: AlpnId,
        srchost: &str,
        srcport: u16,
    ) -> Result<()> {
        // (1) Initial check for the magic "clear" keyword: the text up to the
        //     first ';' or CR/LF, trimmed, compared case-insensitively.
        {
            let mut c = Parser::new(value);
            if let Some(tok) = c.take_cspn(b";\n\r") {
                if trim_blanks(tok).eq_ignore_ascii_case("clear") {
                    self.flush(srcalpnid, srchost, srcport);
                    return Ok(());
                }
            }
        }

        // (2) Parse the comma-separated list of alternatives.
        let mut p = Parser::new(value);
        let mut alpn = match p.take_until(MAX_ALTSVC_LINE, b'=') {
            Some(a) => trim_blanks(a),
            None => return Ok(()), // strange line: nothing before '='
        };
        let mut entries: usize = 0;

        loop {
            if !p.eat_char(b'=') {
                break;
            }
            let dstalpnid = AlpnId::from_alpn(alpn);
            let mut maxage: i64 = 24 * 3600; // default max-age is 24 hours
            let mut persist = false;

            if !p.eat_char(b'"') {
                break; // no opening quote after '='
            }

            // Destination host — defaults to the source host when absent.
            let dsthost: String;
            if !p.eat_char(b':') {
                // A host token is present.
                if !p.eat_char(b'[') {
                    // Regular host name, up to the ':' port separator.
                    match p.take_until(MAX_ALTSVC_HOSTLEN, b':') {
                        Some(h) => dsthost = h.to_string(),
                        None => {
                            tracing::info!("Bad alt-svc hostname, ignoring.");
                            break;
                        }
                    }
                } else {
                    // Bracketed IPv6 literal, up to the ']'.
                    match p.take_until(MAX_IPADR_LEN, b']') {
                        Some(h) if p.eat_char(b']') => dsthost = h.to_string(),
                        _ => {
                            tracing::info!("Bad alt-svc IPv6 hostname, ignoring.");
                            break;
                        }
                    }
                }
                if !p.eat_char(b':') {
                    break; // expected ':' before the port
                }
            } else {
                // No destination name given: reuse the source host.
                dsthost = srchost.to_string();
            }

            // Port.
            let dstport = match p.take_number(0xffff) {
                Some(n) => n as u16,
                None => {
                    tracing::info!("Unknown alt-svc port number, ignoring.");
                    break;
                }
            };

            if !p.eat_char(b'"') {
                break; // expected the closing quote
            }

            // (3) Optional ';'-separated parameters: 'ma', 'persist', others
            //     silently skipped.
            p.pass_blanks();
            if p.eat_char(b';') {
                // Each iteration consumes one `name=value` parameter; the loop
                // ends when no further name token is present (curl's
                // `curlx_str_until(&p, &name, 20, '=')` failing).
                while let Some(name) = p.take_until(20, b'=') {
                    if !p.eat_char(b'=') {
                        break;
                    }
                    let value_start = p.pos();
                    let raw_val = match p.take_cspn(b",;") {
                        Some(v) => v,
                        None => break,
                    };
                    let name = trim_blanks(name);
                    // The value may be quoted; count leading blanks so the
                    // number is parsed from exactly where curl's `vp` points.
                    // Byte-oriented to match `curlx_str_trimblanks` (ISBLANK).
                    let leading = raw_val
                        .bytes()
                        .take_while(|&b| b == b' ' || b == b'\t')
                        .count();
                    let trimmed = trim_blanks(raw_val);
                    let quoted = trimmed.as_bytes().first() == Some(&b'"');
                    let number_start = value_start + leading + usize::from(quoted);
                    p.set_pos(number_start);
                    match p.take_number(TIME_T_MAX) {
                        Some(num) => {
                            if name.eq_ignore_ascii_case("ma") {
                                maxage = num;
                            } else if name.eq_ignore_ascii_case("persist") && num == 1 {
                                persist = true;
                            }
                        }
                        None => break,
                    }
                    // `p` now sits just past the parsed number.
                    p.pass_blanks();
                    if quoted && !p.eat_char(b'"') {
                        break;
                    }
                    p.pass_blanks();
                    if !p.eat_char(b';') {
                        break;
                    }
                }
            }

            // (4) Commit the alternative. Unknown protocols are skipped.
            if dstalpnid != AlpnId::None {
                if entries == 0 {
                    // The first alternative on a line replaces the origin's set.
                    self.flush(srcalpnid, srchost, srcport);
                }
                entries += 1;
                if let Some(mut entry) =
                    create_id(srchost, &dsthost, srcalpnid, dstalpnid, srcport, dstport)
                {
                    let secs = now_secs();
                    // RFC 7838 §3.1: fold max-age into an absolute expiry,
                    // capping at TIME_T_MAX on overflow.
                    entry.expires = if maxage > TIME_T_MAX - secs {
                        TIME_T_MAX
                    } else {
                        maxage + secs
                    };
                    entry.persist = persist;
                    tracing::info!(
                        "Added alt-svc: {}:{} over {}",
                        dsthost,
                        dstport,
                        dstalpnid.as_str()
                    );
                    self.entries.push(entry);
                }
            }

            // (5) A comma introduces another alternative; anything else ends
            //     the header.
            if !p.eat_char(b',') {
                break;
            }
            alpn = match p.take_until(MAX_ALTSVC_LINE, b'=') {
                Some(a) => trim_blanks(a),
                None => break,
            };
        }

        Ok(())
    }

    /// Selects a cached alternative service for the origin
    /// `(srcalpnid, srchost, srcport)`, mirroring `Curl_altsvc_lookup`.
    ///
    /// `versions` is a bitmask of acceptable destination protocols built from
    /// [`CURLALTSVC_H1`] / [`CURLALTSVC_H2`] / [`CURLALTSVC_H3`]; a destination
    /// matches when its [`AlpnId::bits`] intersects the mask. Entries whose
    /// expiry has passed are pruned as they are encountered (parity with curl,
    /// which removes expired nodes during the scan).
    ///
    /// Returns the first matching alternative as an owned [`AltSvcMatch`], whose
    /// [`same_destination`](AltSvcMatch::same_destination) flag indicates the
    /// alternative differs from the origin only in protocol.
    #[must_use]
    pub fn lookup(
        &mut self,
        srcalpnid: AlpnId,
        srchost: &str,
        srcport: u16,
        versions: i32,
    ) -> Option<AltSvcMatch> {
        let now = now_secs();
        let mut i = 0;
        while i < self.entries.len() {
            // Prune expired entries in place, exactly as curl does mid-scan.
            if self.entries[i].expires < now {
                self.entries.remove(i);
                continue;
            }
            let e = &self.entries[i];
            if e.src.alpnid == srcalpnid
                && hostcompare(srchost, &e.src.host)
                && e.src.port == srcport
                && (versions & e.dst.alpnid.bits()) != 0
            {
                let same_destination = srcport == e.dst.port && hostcompare(srchost, &e.dst.host);
                return Some(AltSvcMatch {
                    alpnid: e.dst.alpnid,
                    host: e.dst.host.clone(),
                    port: e.dst.port,
                    same_destination,
                });
            }
            i += 1;
        }
        None
    }
}

