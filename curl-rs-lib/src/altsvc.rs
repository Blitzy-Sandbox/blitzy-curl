/// Trims leading and trailing blanks (ASCII space or tab) from `s`, mirroring
/// `curlx_str_trimblanks`.
///
/// Only ASCII space and tab are treated as blank (curl's `ISBLANK`), never
/// newlines or other Unicode whitespace, so the trim is byte-exact.
fn trim_blanks(s: &str) -> &str {
    s.trim_matches(|c: char| c == ' ' || c == '\t')
}

/// Returns `true` when `host` matches `check`, mirroring `hostcompare`
/// (`lib/altsvc.c`).
///
/// A single trailing dot on `host` (the query side) is ignored, and the
/// comparison is ASCII case-insensitive. Because
/// [`str::eq_ignore_ascii_case`] already requires equal lengths, the length
/// pre-check curl performs is subsumed.
fn hostcompare(host: &str, check: &str) -> bool {
    let host = host.strip_suffix('.').unwrap_or(host);
    host.eq_ignore_ascii_case(check)
}

/// Returns `true` when `host` is a bare IPv6 literal, mirroring curl's
/// `curlx_inet_pton(AF_INET6, host, ...)` probe used to decide whether to
/// bracket the host on save. [`Ipv6Addr`]'s parser is strict (no brackets, no
/// zone id), matching `inet_pton`.
fn host_is_ipv6(host: &str) -> bool {
    host.parse::<Ipv6Addr>().is_ok()
}

/// Returns "now" as a Unix timestamp (seconds, UTC).
///
/// In debug builds this honors the `CURL_TIME` environment variable, mirroring
/// curl's `DEBUGBUILD`/`UNITTESTS` `time()` override (used by the alt-svc unit
/// test to pin a deterministic clock). Release builds always use the wall
/// clock. When `CURL_TIME` is set but not a leading decimal number, `0` is
/// returned — matching curl's `altsvc_debugtime`, whose value stays `0` on a
/// parse failure.
fn now_secs() -> i64 {
    if cfg!(debug_assertions) {
        if let Ok(s) = std::env::var("CURL_TIME") {
            let mut p = Parser::new(&s);
            return p.take_number(TIME_T_MAX).unwrap_or(0);
        }
    }
    Utc::now().timestamp()
}

/// Parses a fixed-width all-ASCII-digit byte field into a [`u32`].
///
/// Returns `None` if the field is empty, contains a non-digit, or overflows
/// `u32`. Unlike [`str::parse`], it rejects a leading `+`.
fn digits(b: &[u8]) -> Option<u32> {
    if b.is_empty() || !b.iter().all(u8::is_ascii_digit) {
        return None;
    }
    let mut v: u32 = 0;
    for &c in b {
        v = v.checked_mul(10)?.checked_add(u32::from(c - b'0'))?;
    }
    Some(v)
}

/// Parses the canonical on-disk date `YYYYMMDD HH:MM:SS` (UTC) into a Unix
/// timestamp.
///
/// This is the exact 17-byte layout curl writes (and reads back via its general
/// date parser). Any deviation — wrong length, misplaced separators, or an
/// out-of-range calendar value — yields `None`, in which case the caller leaves
/// the entry's expiry at `0` (parity with curl ignoring `Curl_getdate_capped`'s
/// return value).
fn parse_altsvc_date(s: &str) -> Option<i64> {
    let b = s.as_bytes();
    if b.len() != MAX_ALTSVC_DATELEN || b[8] != b' ' || b[11] != b':' || b[14] != b':' {
        return None;
    }
    let year = digits(&b[0..4])? as i32;
    let month = digits(&b[4..6])?;
    let day = digits(&b[6..8])?;
    let hour = digits(&b[9..11])?;
    let minute = digits(&b[12..14])?;
    let second = digits(&b[15..17])?;

    let date = NaiveDate::from_ymd_opt(year, month, day)?;
    let datetime = date.and_hms_opt(hour, minute, second)?;
    Some(datetime.and_utc().timestamp())
}

/// Breaks a Unix timestamp down into `(year, month, day, hour, minute, second)`
/// in UTC, mirroring `curlx_gmtime`.
///
/// # Errors
///
/// Returns [`Error::BadFunctionArgument`] when the timestamp is outside the
/// range chrono can represent as a calendar date (mirrors a `gmtime` failure,
/// which curl surfaces as `CURLE_BAD_FUNCTION_ARGUMENT`).
fn gmtime_fields(secs: i64) -> Result<(i32, u32, u32, u32, u32, u32)> {
    match DateTime::<Utc>::from_timestamp(secs, 0) {
        Some(dt) => {
            let n = dt.naive_utc();
            Ok((
                n.year(),
                n.month(),
                n.day(),
                n.hour(),
                n.minute(),
                n.second(),
            ))
        }
        None => Err(Error::bad_argument(
            "alt-svc expiry timestamp out of representable range",
        )),
    }
}

/// Serializes one [`AltSvcEntry`] to its nine-field on-disk line (terminated
/// by `\n`), mirroring `altsvc_out` (`lib/altsvc.c`).
///
/// The field order and formatting are byte-identical to curl's
/// `curl_mfprintf`: source `alpn host port`, destination `alpn host port`, a
/// quoted `"YYYYMMDD HH:MM:SS"` expiry, then the `persist` and `prio` integers.
/// IPv6 literal hosts are wrapped in brackets.
fn entry_to_line(e: &AltSvcEntry) -> Result<String> {
    let (year, month, day, hour, minute, second) = gmtime_fields(e.expires)?;
    let (src_pre, src_post) = if host_is_ipv6(&e.src.host) {
        ("[", "]")
    } else {
        ("", "")
    };
    let (dst_pre, dst_post) = if host_is_ipv6(&e.dst.host) {
        ("[", "]")
    } else {
        ("", "")
    };
    Ok(format!(
        "{} {}{}{} {} {} {}{}{} {} \"{}{:02}{:02} {:02}:{:02}:{:02}\" {} {}\n",
        e.src.alpnid.as_str(),
        src_pre,
        e.src.host,
        src_post,
        e.src.port,
        e.dst.alpnid.as_str(),
        dst_pre,
        e.dst.host,
        dst_post,
        e.dst.port,
        year,
        month,
        day,
        hour,
        minute,
        second,
        u8::from(e.persist),
        e.prio,
    ))
}

/// Builds an [`AltSvcEntry`] from raw host/port/alpn values, mirroring
/// `altsvc_createid` (`lib/altsvc.c`).
///
/// Host normalization matches curl exactly: the **source** host has any
/// surrounding IPv6 brackets stripped, or otherwise a single trailing dot; the
/// **destination** host only has brackets stripped. A host that is empty after
/// normalization causes the whole entry to be rejected (`None`). `expires`,
/// `persist`, and `prio` are initialized to zero/false and set by the caller.
fn create_id(
    srchost: &str,
    dsthost: &str,
    srcalpnid: AlpnId,
    dstalpnid: AlpnId,
    srcport: u16,
    dstport: u16,
) -> Option<AltSvcEntry> {
    let sh = strip_host(srchost, true);
    let dh = strip_host(dsthost, false);
    if sh.is_empty() || dh.is_empty() {
        return None;
    }
    Some(AltSvcEntry {
        src: AltHost {
            host: sh.to_string(),
            port: srcport,
            alpnid: srcalpnid,
        },
        dst: AltHost {
            host: dh.to_string(),
            port: dstport,
            alpnid: dstalpnid,
        },
        expires: 0,
        persist: false,
        prio: 0,
    })
}

/// Normalizes a host per `altsvc_createid`: strips surrounding IPv6 brackets,
/// and — only when `strip_trailing_dot` is set (the source side) — a single
/// trailing dot. The bracket rule mirrors curl's assumption of a matching
/// trailing `]` when the host begins with `[` and is longer than two bytes.
fn strip_host(host: &str, strip_trailing_dot: bool) -> &str {
    let bytes = host.as_bytes();
    if bytes.len() > 2 && bytes[0] == b'[' {
        &host[1..host.len() - 1]
    } else if strip_trailing_dot && bytes.last() == Some(&b'.') {
        &host[..host.len() - 1]
    } else {
        host
    }
}

/// Parses one nine-field cache line into an [`AltSvcEntry`], mirroring
/// `altsvc_add` + `altsvc_create` (`lib/altsvc.c`).
///
/// Fields are separated by exactly one space. Any tokenization failure yields
/// `None` (the whole line is skipped, as curl's loader ignores per-line
/// errors). An unknown ALPN token on either side, or an empty normalized host,
/// also rejects the line. `prio` is forced to `0` and `persist` is coerced to a
/// boolean, exactly as curl does on load.
fn parse_file_line(line: &str) -> Option<AltSvcEntry> {
    let mut p = Parser::new(line);

    let src_alpn = p.take_word(MAX_ALTSVC_ALPNLEN)?;
    if !p.eat_char(b' ') {
        return None;
    }
    let src_host = p.take_word(MAX_ALTSVC_HOSTLEN)?;
    if !p.eat_char(b' ') {
        return None;
    }
    let src_port = p.take_number(65535)?;
    if !p.eat_char(b' ') {
        return None;
    }
    let dst_alpn = p.take_word(MAX_ALTSVC_ALPNLEN)?;
    if !p.eat_char(b' ') {
        return None;
    }
    let dst_host = p.take_word(MAX_ALTSVC_HOSTLEN)?;
    if !p.eat_char(b' ') {
        return None;
    }
    let dst_port = p.take_number(65535)?;
    if !p.eat_char(b' ') {
        return None;
    }
    let date = p.take_quoted(MAX_ALTSVC_DATELEN)?;
    if !p.eat_char(b' ') {
        return None;
    }
    let persist = p.take_number(1)?;
    if !p.eat_char(b' ') {
        return None;
    }
    // `prio` is bounded to 0 by curl (max = 0) and always stored as 0.
    let _prio = p.take_number(0)?;
    if !p.expect_newline_or_end() {
        return None;
    }

    let src_alpnid = AlpnId::from_alpn(src_alpn);
    let dst_alpnid = AlpnId::from_alpn(dst_alpn);
    if src_alpnid == AlpnId::None || dst_alpnid == AlpnId::None {
        return None;
    }

    let mut entry = create_id(
        src_host,
        dst_host,
        src_alpnid,
        dst_alpnid,
        src_port as u16,
        dst_port as u16,
    )?;
    entry.expires = parse_altsvc_date(date).unwrap_or(0);
    entry.persist = persist != 0;
    entry.prio = 0;
    Some(entry)
}

// ---------------------------------------------------------------------------
// Internal byte-oriented string cursor
//
// A faithful, offset-based reimplementation of the subset of curl's
// `curlx_str_*` tokenizers used by alt-svc. Using a byte offset into the full
// input (rather than shrinking sub-slices) is essential: curl's header parser
// resets its cursor to a position *inside* a previously extracted token and
// then continues reading past that token's end (the `p = vp` idiom), which is
// only expressible against the complete backing string.
//
// All tokenizers operate on bytes; delimiters, digits and blanks are ASCII, so
// every slice boundary this cursor produces lands on a UTF-8 char boundary.
// ---------------------------------------------------------------------------

struct Parser<'a> {
    full: &'a str,
    pos: usize,
}

impl<'a> Parser<'a> {
    /// Creates a cursor positioned at the start of `s`.
    fn new(s: &'a str) -> Self {
        Parser { full: s, pos: 0 }
    }

    /// Returns the current byte offset.
    fn pos(&self) -> usize {
        self.pos
    }

    /// Moves the cursor to an absolute byte offset (clamped to the input end).
    /// Callers only ever pass offsets that fall on ASCII boundaries.
    fn set_pos(&mut self, pos: usize) {
        self.pos = pos.min(self.full.len());
    }

    /// Returns the not-yet-consumed remainder of the input.
    fn remaining(&self) -> &'a str {
        &self.full[self.pos..]
    }

    /// Returns the byte at the cursor, or `None` at end of input.
    fn first(&self) -> Option<u8> {
        self.full.as_bytes().get(self.pos).copied()
    }

    /// Advances over any leading blanks (space or tab), mirroring
    /// `curlx_str_passblanks`.
    fn pass_blanks(&mut self) {
        let b = self.full.as_bytes();
        while self.pos < b.len() && (b[self.pos] == b' ' || b[self.pos] == b'\t') {
            self.pos += 1;
        }
    }

    /// Consumes a single expected byte, mirroring `curlx_str_single`. Returns
    /// `true` (and advances) on a match, `false` (leaving the cursor put)
    /// otherwise.
    fn eat_char(&mut self, c: u8) -> bool {
        if self.first() == Some(c) {
            self.pos += 1;
            true
        } else {
            false
        }
    }

    /// Reads a token of `1..=max` bytes up to (but not consuming) `delim` or the
    /// end of input, mirroring `curlx_str_until`. Returns `None` when the token
    /// would be empty (`STRE_SHORT`) or exceed `max` (`STRE_BIG`).
    fn take_until(&mut self, max: usize, delim: u8) -> Option<&'a str> {
        let b = self.full.as_bytes();
        let start = self.pos;
        let mut i = start;
        let mut len = 0usize;
        while i < b.len() && b[i] != delim {
            i += 1;
            len += 1;
            if len > max {
                return None;
            }
        }
        if len == 0 {
            return None;
        }
        self.pos = i;
        Some(&self.full[start..i])
    }

    /// Reads a token up to the next space, mirroring `curlx_str_word`.
    fn take_word(&mut self, max: usize) -> Option<&'a str> {
        self.take_until(max, b' ')
    }

    /// Reads a double-quoted token, mirroring `curlx_str_quotedword`.
    ///
    /// The surrounding quotes are stripped from the returned slice; an escaped
    /// quote (`\"`) does not terminate the token but the backslash is **kept**
    /// in the returned bytes (exactly as curl, which counts but does not unescape
    /// it). Returns `None` on a missing opening/closing quote or on exceeding
    /// `max` inner bytes.
    fn take_quoted(&mut self, max: usize) -> Option<&'a str> {
        let b = self.full.as_bytes();
        let start = self.pos;
        if b.get(start) != Some(&b'"') {
            return None; // STRE_BEGQUOTE
        }
        let mut i = start + 1;
        let mut len = 0usize;
        while i < b.len() && b[i] != b'"' {
            if b[i] == b'\\' && i + 1 < b.len() {
                i += 1;
                len += 1;
                if len > max {
                    return None;
                }
            }
            i += 1;
            len += 1;
            if len > max {
                return None;
            }
        }
        if b.get(i) != Some(&b'"') {
            return None; // STRE_ENDQUOTE
        }
        let inner = &self.full[start + 1..i];
        self.pos = i + 1;
        Some(inner)
    }

    /// Reads an unsigned base-10 number capped at `max`, mirroring
    /// `curlx_str_number` (no sign, no `0x`, leading zeros accepted). Returns
    /// `None` when there is no leading digit (`STRE_NO_NUM`) or the value would
    /// exceed `max` (`STRE_OVERFLOW`). The two-branch structure mirrors curl's
    /// own overflow handling for small vs. large `max`.
    fn take_number(&mut self, max: i64) -> Option<i64> {
        let b = self.full.as_bytes();
        let start = self.pos;
        match b.get(start) {
            Some(c) if c.is_ascii_digit() => {}
            _ => return None,
        }
        let mut num: i64 = 0;
        let mut i = start;
        if max < 10 {
            loop {
                let n = i64::from(b[i] - b'0');
                num = num * 10 + n;
                if num > max {
                    return None;
                }
                i += 1;
                if i >= b.len() || !b[i].is_ascii_digit() {
                    break;
                }
            }
        } else {
            loop {
                let n = i64::from(b[i] - b'0');
                if num > (max - n) / 10 {
                    return None;
                }
                num = num * 10 + n;
                i += 1;
                if i >= b.len() || !b[i].is_ascii_digit() {
                    break;
                }
            }
        }
        self.pos = i;
        Some(num)
    }

    /// Reads the run of bytes that are **not** in `reject` (nor end of input),
    /// mirroring `curlx_str_cspn`. Returns `None` when the run is empty.
    fn take_cspn(&mut self, reject: &[u8]) -> Option<&'a str> {
        let b = self.full.as_bytes();
        let start = self.pos;
        let mut i = start;
        while i < b.len() && !reject.contains(&b[i]) {
            i += 1;
        }
        if i == start {
            return None;
        }
        self.pos = i;
        Some(&self.full[start..i])
    }

    /// Accepts a CR or LF (consuming it) or end of input, mirroring
    /// `curlx_str_newline`.
    ///
    /// End of input is treated as a valid line terminator because
    /// `Curl_get_line` guarantees every parsed line ends in a newline; a
    /// stripped trailing newline is therefore functionally equivalent.
    fn expect_newline_or_end(&mut self) -> bool {
        match self.first() {
            None => true,
            Some(b'\n' | b'\r') => {
                self.pos += 1;
                true
            }
            Some(_) => false,
        }
    }
}

