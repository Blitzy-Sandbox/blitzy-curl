    #[test]
    fn clear_flushes_matching_origin_only() {
        let _guard = TIME_LOCK.lock().unwrap_or_else(|e| e.into_inner());
        std::env::set_var("CURL_TIME", CURL_TIME_FIXED);

        let mut asi = AltSvc::new();
        asi.parse("h2=\":443\"\r\n", AlpnId::H1, "a.example", 80)
            .unwrap();
        asi.parse("h3=\":443\"\r\n", AlpnId::H1, "b.example", 80)
            .unwrap();
        assert_eq!(asi.len(), 2);

        // "clear" only affects the (h1, a.example, 80) origin.
        asi.parse("clear\r\n", AlpnId::H1, "a.example", 80).unwrap();
        assert_eq!(asi.len(), 1);
        assert_eq!(asi.entries()[0].src.host, "b.example");

        // A different origin's clear removes nothing more here.
        asi.parse("clear;\r\n", AlpnId::H2, "b.example", 80)
            .unwrap();
        assert_eq!(asi.len(), 1);
    }

    // Time-exact: depends on the `CURL_TIME` override, which `now_secs()` only
    // honors in debug builds (parity with curl's `#if defined(DEBUGBUILD) ||
    // defined(UNITTESTS)` guard on `altsvc_debugtime` and unit1654).
    #[test]
    #[cfg(debug_assertions)]
    fn lookup_matches_version_mask_and_prunes_expired() {
        let _guard = TIME_LOCK.lock().unwrap_or_else(|e| e.into_inner());
        std::env::set_var("CURL_TIME", CURL_TIME_FIXED);
        let now: i64 = CURL_TIME_FIXED.parse().unwrap();

        let mut asi = AltSvc::new();
        // A live h3 alternative for (h1, origin.example, 443).
        asi.entries.push(AltSvcEntry {
            src: AltHost {
                host: "origin.example".into(),
                port: 443,
                alpnid: AlpnId::H1,
            },
            dst: AltHost {
                host: "alt.example".into(),
                port: 8443,
                alpnid: AlpnId::H3,
            },
            expires: now + 3600,
            persist: false,
            prio: 0,
        });

        // Version mask excludes H3 -> no match.
        assert!(asi
            .lookup(
                AlpnId::H1,
                "origin.example",
                443,
                (CURLALTSVC_H1 | CURLALTSVC_H2) as i32
            )
            .is_none());

        // Version mask includes H3 -> match, different destination.
        let m = asi
            .lookup(AlpnId::H1, "origin.example", 443, CURLALTSVC_H3 as i32)
            .expect("expected an h3 match");
        assert_eq!(m.alpnid, AlpnId::H3);
        assert_eq!(m.host, "alt.example");
        assert_eq!(m.port, 8443);
        assert!(!m.same_destination);

        // A same-destination alternative (only the protocol differs).
        let mut asi2 = AltSvc::new();
        asi2.entries.push(AltSvcEntry {
            src: AltHost {
                host: "same.example".into(),
                port: 443,
                alpnid: AlpnId::H1,
            },
            dst: AltHost {
                host: "same.example".into(),
                port: 443,
                alpnid: AlpnId::H2,
            },
            expires: now + 3600,
            persist: false,
            prio: 0,
        });
        let m2 = asi2
            .lookup(AlpnId::H1, "same.example", 443, CURLALTSVC_H2 as i32)
            .expect("expected an h2 match");
        assert!(m2.same_destination);

        // Expired entries are pruned during the scan and never matched.
        let mut asi3 = AltSvc::new();
        asi3.entries.push(AltSvcEntry {
            src: AltHost {
                host: "old.example".into(),
                port: 443,
                alpnid: AlpnId::H1,
            },
            dst: AltHost {
                host: "old.example".into(),
                port: 8443,
                alpnid: AlpnId::H3,
            },
            expires: now - 1, // already expired
            persist: false,
            prio: 0,
        });
        assert!(asi3
            .lookup(AlpnId::H1, "old.example", 443, CURLALTSVC_H3 as i32)
            .is_none());
        assert!(asi3.is_empty(), "expired entry must be pruned");
    }

    // ---- The full unit1654 byte-exact oracle -------------------------------

    // Time-exact byte oracle — debug-only, mirroring curl's unit1654 which is
    // itself gated behind DEBUGBUILD/UNITTESTS (it relies on the CURL_TIME
    // clock override to produce deterministic expiry timestamps).
    #[test]
    #[cfg(debug_assertions)]
    fn unit1654_load_parse_save_is_byte_exact() {
        let _guard = TIME_LOCK.lock().unwrap_or_else(|e| e.into_inner());
        std::env::set_var("CURL_TIME", CURL_TIME_FIXED);

        // The input cache file (line 5 begins with a real TAB; two lines carry
        // leading blanks; `bad`/`rubbish` lines are intentionally invalid).
        let input = concat!(
            "h2 example.com 443 h3 shiny.example.com 8443 \"20191231 00:00:00\" 0 0\n",
            "# a comment\n",
            "h2 foo.example.com 443 h3 shiny.example.com 8443 \"20291231 23:30:00\" 0 0\n",
            "  h1 example.com 443 h3 shiny.example.com 8443 \"20121231 00:00:01\" 0 0\n",
            "\th3 example.com 443 h3 shiny.example.com 8443 \"20131231 00:00:00\" 0 0\n",
            "    # also a comment\n",
            "bad example.com 443 h3 shiny.example.com 8443 \"20191231 00:00:00\" 0 0\n",
            "rubbish\n",
        );
        let expected = concat!(
            "# Your alt-svc cache. https://curl.se/docs/alt-svc.html\n",
            "# This file was generated by libcurl! Edit at your own risk.\n",
            "h2 example.com 443 h3 shiny.example.com 8443 \"20191231 00:00:00\" 0 0\n",
            "h2 foo.example.com 443 h3 shiny.example.com 8443 \"20291231 23:30:00\" 0 0\n",
            "h1 example.com 443 h3 shiny.example.com 8443 \"20121231 00:00:01\" 0 0\n",
            "h3 example.com 443 h3 shiny.example.com 8443 \"20131231 00:00:00\" 0 0\n",
            "h1 example.org 8080 h2 example.com 8080 \"20190125 22:34:21\" 0 0\n",
            "h1 2.example.org 8080 h3 2.example.org 8080 \"20190125 22:34:21\" 0 0\n",
            "h1 3.example.org 8080 h2 example.com 8080 \"20190125 22:34:21\" 0 0\n",
            "h1 3.example.org 8080 h3 yesyes.com 8080 \"20190125 22:34:21\" 0 0\n",
            "h2 example.org 80 h2 example.com 443 \"20190124 22:36:21\" 0 0\n",
            "h2 example.net 80 h2 example.net 443 \"20190124 22:37:21\" 0 0\n",
            "h2 test.se 443 h2 test2.se 443 \"20190124 22:37:21\" 0 0\n",
            "h2 test.se 443 h2 test3.se 443 \"20190124 22:36:21\" 0 0\n",
        );

        let in_path = temp_path("1654-in");
        let out_path = temp_path("1654-out");
        fs::write(&in_path, input).unwrap();

        let mut asi = AltSvc::new();
        asi.load(&in_path).unwrap();
        assert_eq!(asi.len(), 4, "load: wrong number of entries");

        asi.parse(
            "h2=\"example.com:8080\"\r\n",
            AlpnId::H1,
            "example.org",
            8080,
        )
        .unwrap();
        assert_eq!(asi.len(), 5);

        asi.parse("h3=\":8080\"\r\n", AlpnId::H1, "2.example.org", 8080)
            .unwrap();
        assert_eq!(asi.len(), 6);

        asi.parse(
            "h2=\"example.com:8080\", h3=\"yesyes.com:8080\"\r\n",
            AlpnId::H1,
            "3.example.org",
            8080,
        )
        .unwrap();
        assert_eq!(asi.len(), 8, "that header should make two entries");

        asi.parse(
            "h2=\"example.com:443\"; ma = 120;\r\n",
            AlpnId::H2,
            "example.org",
            80,
        )
        .unwrap();
        assert_eq!(asi.len(), 9);

        asi.parse(
            "h2=\"example.net:443\"; ma=\"180\";\r\n",
            AlpnId::H2,
            "example.net",
            80,
        )
        .unwrap();
        assert_eq!(asi.len(), 10);

        asi.parse(
            "h2=\":443\"; ma=180, h3=\":443\"; persist = \"1\"; ma = 120;\r\n",
            AlpnId::H1,
            "curl.se",
            80,
        )
        .unwrap();
        assert_eq!(asi.len(), 12);

        asi.parse("clear;\r\n", AlpnId::H1, "curl.se", 80).unwrap();
        assert_eq!(asi.len(), 10, "clear; should drop the two curl.se entries");

        asi.parse(
            "h2=\":443\", h3=\":443\"; persist = \"1\"; ma = 120;\r\n",
            AlpnId::H1,
            "curl.se",
            80,
        )
        .unwrap();
        assert_eq!(asi.len(), 12);

        asi.parse("clear\r\n", AlpnId::H1, "curl.se", 80).unwrap();
        assert_eq!(asi.len(), 10, "clear (no semicolon) should also drop them");

        // Non-existing alpn: rejected, no change.
        asi.parse(
            "h6=\"example.net:443\"; ma=\"180\";\r\n",
            AlpnId::H2,
            "5.example.net",
            80,
        )
        .unwrap();
        assert_eq!(asi.len(), 10);

        // Missing quote in host: rejected.
        asi.parse(
            "h2=\"example.net:443,; ma=\"180\";\r\n",
            AlpnId::H2,
            "6.example.net",
            80,
        )
        .unwrap();
        assert_eq!(asi.len(), 10);

        // Missing port in hostname: rejected.
        asi.parse(
            "h2=\"example.net\"; ma=\"180\";\r\n",
            AlpnId::H2,
            "7.example.net",
            80,
        )
        .unwrap();
        assert_eq!(asi.len(), 10);

        // Illegal port (70000 > 65535): rejected.
        asi.parse(
            "h2=\"example.net:70000\"; ma=\"180\";\r\n",
            AlpnId::H2,
            "8.example.net",
            80,
        )
        .unwrap();
        assert_eq!(asi.len(), 10);

        // A quoted 'ma' with trailing space, an unknown flag, then a second
        // comma-separated alternative -> two new entries.
        asi.parse(
            "h2=\"test2.se:443\"; ma=\"180 \" ; unknown=2, h2=\"test3.se:443\"; ma = 120;\r\n",
            AlpnId::H2,
            "test.se",
            443,
        )
        .unwrap();
        assert_eq!(asi.len(), 12);

        // Save and diff against curl 8.x's expected byte stream.
        asi.save(Some(&out_path)).unwrap();
        let got = fs::read_to_string(&out_path).unwrap();
        assert_eq!(
            got, expected,
            "saved cache is not byte-identical to curl 8.x"
        );

        // Reloading the saved file yields the identical entry set and re-saves
        // to the same bytes (full save->load->save round-trip).
        let mut reloaded = AltSvc::new();
        reloaded.load(&out_path).unwrap();
        assert_eq!(reloaded.entries(), asi.entries());
        let out_path2 = temp_path("1654-out2");
        reloaded.save(Some(&out_path2)).unwrap();
        assert_eq!(fs::read_to_string(&out_path2).unwrap(), expected);

        let _ = fs::remove_file(&in_path);
        let _ = fs::remove_file(&out_path);
        let _ = fs::remove_file(&out_path2);
    }
