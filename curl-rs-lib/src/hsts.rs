//! HTTP Strict Transport Security (HSTS) cache — RFC 6797.
//!
//! This module is a faithful, behavior-preserving Rust port of curl's
//! `lib/hsts.c` (and its declaration companion `lib/hsts.h`). It maintains the
//! in-memory HSTS store, persists it to (and loads it from) the on-disk cache
//! file, ingests `Strict-Transport-Security` response headers, and answers the
//! single question the transfer layer asks before every `http://` request:
//! *"is this host known-HSTS, and must therefore be upgraded to `https://`?"*
//! (In curl this is the `Curl_hsts(..., TRUE)` call at `lib/url.c`.)
//!
//! # Parity contract
//!
//! The persisted file format is **byte-compatible** with curl 8.x, which is a
//! hard requirement (AAP §0.6.3): a file written by this module must be
//! readable by a curl 8.x reference binary and vice-versa. Concretely, the
//! writer reproduces curl's exact output:
//!
//! ```text
//! # Your HSTS cache. https://curl.se/docs/hsts.html
//! # This file was generated by libcurl! Edit at your own risk.
//! .example.com "20370101 00:00:00"
//! example.net "unlimited"
//! ```
//!
//! Each entry line is `curl_mfprintf(fp, "%s%s \"%s\"\n", …)` in the C source:
//! an optional leading `.` when the entry carries `includeSubDomains`, then the
//! host, a space, then a double-quoted expiry stamp. The stamp is either
//! `YYYYMMDD HH:MM:SS` in UTC (formatted exactly like curl's
//! `"%d%02d%02d %02d:%02d:%02d"`) or the sentinel string `unlimited` for
//! entries that never expire.
//!
//! # Matching semantics
//!
//! [`Hsts::is_hsts`] mirrors curl's `Curl_hsts`: it strips a single trailing
//! dot from the query name, ignores expired entries, returns immediately on an
//! exact (ASCII case-insensitive) host match, and otherwise honors the
//! *longest* `includeSubDomains` tail match. A tail match requires the stored
//! host to be strictly shorter than the query (`ntail < hlen`), the byte
//! immediately preceding the tail in the query to be a `.`, and the tail bytes
//! to compare equal case-insensitively — precisely the rule in `hsts.c`.
//!
//! # Header ingestion
//!
//! [`Hsts::parse`] mirrors `Curl_hsts_parse`: it walks the header's
//! `;`-separated directives, recognizing `max-age` (mandatory) and
//! `includeSubDomains` (the `preload` token is ignored), rejecting duplicates,
//! and applying RFC 6797 rules — `max-age=0` deletes an existing entry, IP
//! address hosts are excluded entirely, and an overflowing `max-age` saturates
//! to the "unlimited" sentinel.
//!
//! # Callback parity
//!
//! curl exposes `CURLOPT_HSTSREADFUNCTION` / `CURLOPT_HSTSWRITEFUNCTION` so an
//! application can supply / receive entries programmatically. Those C hook
//! points are preserved (AAP §0.6.1); this module exposes the Rust-side hooks
//! ([`Hsts::load_from_callback`] / [`Hsts::save_to_callback`], driven by
//! [`HstsEntry`] and [`HstsCode`]) that the FFI trampoline in `curl-rs-ffi`
//! wires the C callbacks onto.
//!
//! # Feature gating
//!
//! In the C tree this file is compiled only when
//! `!defined(CURL_DISABLE_HTTP) && !defined(CURL_DISABLE_HSTS)`. In the Rust
//! workspace the equivalent gate is applied at the `mod hsts;` declaration in
//! the crate root (under the default-on `http` feature), so this file is kept
//! self-contained and dependency-light.
//!
//! # Safety
//!
//! This module is written entirely in safe Rust: it performs no raw-pointer
//! manipulation and never panics on file- or network-derived input (every
//! fallible operation returns an [`Error`]). The token that denotes non-safe
//! Rust is intentionally absent from this file so the crate-wide `grep` audit
//! stays green.

