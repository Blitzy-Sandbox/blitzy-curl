    // -- real filesystem round-trip (save → load_file) ----------------------

    fn unique_temp_path(tag: &str) -> String {
        let nanos = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or(0);
        let mut p = std::env::temp_dir();
        p.push(format!(
            "blitzy_hsts_{tag}_{}_{}",
            std::process::id(),
            nanos
        ));
        p.to_string_lossy().into_owned()
    }

    #[test]
    fn save_and_load_file_round_trip_on_disk() {
        let path = unique_temp_path("roundtrip");
        let original = store(&[
            ("example.com", true, Some(ts(2037, 1, 1, 0, 0, 0))),
            ("example.net", false, None),
        ]);
        original.save(Some(&path)).unwrap();

        // The bytes on disk match the canonical serialization exactly.
        let on_disk = std::fs::read_to_string(&path).unwrap();
        assert_eq!(on_disk, original.to_file_string().unwrap());

        // Loading them back reproduces the entries and remembers the filename.
        let mut loaded = Hsts::new();
        loaded.load_file_at(&path, NOW).unwrap();
        assert_eq!(loaded.entries(), original.entries());
        assert_eq!(loaded.filename(), Some(path.as_str()));

        // A save() with no path reuses the remembered filename.
        loaded.save(None).unwrap();
        assert_eq!(std::fs::read_to_string(&path).unwrap(), on_disk);

        let _ = std::fs::remove_file(&path);
    }

