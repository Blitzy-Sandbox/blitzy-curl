/// The HSTS cache.
///
/// Mirrors curl's `struct hsts`:
///
/// ```c
/// struct hsts {
///   struct Curl_llist list;
///   char *filename;
///   unsigned int flags;
/// };
/// ```
///
/// The intrusive list becomes a [`Vec<StsEntry>`] that preserves insertion
/// order — this is what makes the saved file byte-identical to curl's, since
/// curl appends new entries at the list tail and writes them in list order.
/// `filename` is retained so that a later [`save`](Hsts::save) with no explicit
/// path reuses the path the cache was loaded from (matching curl's behavior of
/// keeping the name so it "survives an easy handle reset"). `flags` carries the
/// `CURLHSTS_*` bits.
#[derive(Debug, Clone, Default)]
pub struct Hsts {
    /// Entries in insertion order (curl's `Curl_llist`).
    entries: Vec<StsEntry>,
    /// The cache file path remembered from a load, reused by `save(None)`.
    filename: Option<String>,
    /// `CURLHSTS_*` flag bits (notably [`CURLHSTS_READONLYFILE`]).
    flags: u32,
}

impl Hsts {
    /// Creates an empty HSTS cache.
    ///
    /// Mirrors `Curl_hsts_init`.
    #[must_use]
    pub fn new() -> Self {
        Hsts {
            entries: Vec::new(),
            filename: None,
            flags: 0,
        }
    }

    /// Returns the current `CURLHSTS_*` flag bits.
    #[must_use]
    pub fn flags(&self) -> u32 {
        self.flags
    }

    /// Replaces the `CURLHSTS_*` flag bits wholesale.
    pub fn set_flags(&mut self, flags: u32) {
        self.flags = flags;
    }

    /// Sets or clears the [`CURLHSTS_READONLYFILE`] bit.
    ///
    /// When set, [`save`](Hsts::save) never touches the backing file (the
    /// callback path still runs), matching curl's `CURLHSTS_READONLYFILE`
    /// handling in `Curl_hsts_save`.
    pub fn set_readonly(&mut self, readonly: bool) {
        if readonly {
            self.flags |= CURLHSTS_READONLYFILE;
        } else {
            self.flags &= !CURLHSTS_READONLYFILE;
        }
    }

    /// Returns the remembered cache-file path, if any.
    #[must_use]
    pub fn filename(&self) -> Option<&str> {
        self.filename.as_deref()
    }

    /// Returns the number of entries currently stored (curl's
    /// `Curl_llist_count`).
    #[must_use]
    pub fn len(&self) -> usize {
        self.entries.len()
    }

    /// Returns `true` when the cache holds no entries.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    /// Read-only view of the stored entries, in insertion order.
    ///
    /// Primarily useful for the FFI layer and for tests; ordinary transfers use
    /// [`is_hsts`](Hsts::is_hsts).
    #[must_use]
    pub fn entries(&self) -> &[StsEntry] {
        &self.entries
    }
}

