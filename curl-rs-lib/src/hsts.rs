// Header ingestion — mirroring Curl_hsts_parse
// ---------------------------------------------------------------------------

impl Hsts {
    /// Ingests a `Strict-Transport-Security` response header for `hostname`.
    ///
    /// Mirrors `Curl_hsts_parse`. `hostname` is the host the response came
    /// from; `header` is the raw header value (without the field name). See the
    /// module docs for the directive grammar. Returns [`Error::bad_argument`]
    /// (curl's `CURLE_BAD_FUNCTION_ARGUMENT`) for a malformed header, mirroring
    /// curl's error returns.
    pub fn parse(&mut self, hostname: &str, header: &str) -> Result<()> {
        self.parse_at(hostname, header, hsts_now())
    }

    /// [`parse`](Hsts::parse) with an explicit "now", for deterministic tests.
    fn parse_at(&mut self, hostname: &str, header: &str, now: i64) -> Result<()> {
        // RFC 6797 §8.3: IP-address hosts are excluded entirely.
        if is_ip_address(hostname) {
            return Ok(());
        }

        let bytes = header.as_bytes();
        let len = bytes.len();
        let mut p = 0usize;

        let mut expires: i64 = 0;
        let mut got_maxage = false;
        let mut got_include = false;
        let mut subdomains = false;

        // C is a `do { … } while(*p);` loop: the body always runs once, and
        // continues while unconsumed bytes remain.
        loop {
            // curlx_str_passblanks
            while p < len && is_blank(bytes[p]) {
                p += 1;
            }

            if eq_ci_prefix(&bytes[p..], b"max-age") {
                if got_maxage {
                    return Err(Error::bad_argument("duplicate HSTS max-age directive"));
                }
                p += 7;
                while p < len && is_blank(bytes[p]) {
                    p += 1;
                }
                // require '='
                if !(p < len && bytes[p] == b'=') {
                    return Err(Error::bad_argument("HSTS max-age missing '='"));
                }
                p += 1;
                while p < len && is_blank(bytes[p]) {
                    p += 1;
                }
                // optional opening quote
                let quoted = p < len && bytes[p] == b'"';
                if quoted {
                    p += 1;
                }
                match parse_u_number(bytes, &mut p, i64::MAX) {
                    NumParse::Overflow => {
                        // Saturate to the unlimited sentinel; deliberately do
                        // NOT advance `p`, exactly as str_num_base does not.
                        expires = i64::MAX;
                    }
                    NumParse::Ok(v) => expires = v,
                    NumParse::NoNum => {
                        return Err(Error::bad_argument("HSTS max-age is not a number"));
                    }
                }
                if quoted {
                    if !(p < len && bytes[p] == b'"') {
                        return Err(Error::bad_argument("HSTS max-age missing closing quote"));
                    }
                    p += 1;
                }
                got_maxage = true;
            } else if eq_ci_prefix(&bytes[p..], b"includesubdomains") {
                if got_include {
                    return Err(Error::bad_argument("duplicate HSTS includeSubDomains"));
                }
                subdomains = true;
                p += 17;
                got_include = true;
            } else {
                // Unknown directive: a lame attempt to skip to the next ';'.
                while p < len && bytes[p] != b';' {
                    p += 1;
                }
            }

            // curlx_str_passblanks; then consume a single ';' separator.
            while p < len && is_blank(bytes[p]) {
                p += 1;
            }
            if p < len && bytes[p] == b';' {
                p += 1;
            }

            if p >= len {
                break;
            }
        }

        if !got_maxage {
            // max-age is mandatory.
            return Err(Error::bad_argument("HSTS header lacks mandatory max-age"));
        }

        if expires == 0 {
            // max-age=0 removes an existing entry (verbatim, no sub-domain).
            self.remove_exact(hostname, now);
            return Ok(());
        }

        // Absolute expiry = now + max-age, saturating to the unlimited
        // sentinel (curl caps at CURL_OFF_T_MAX, which equals the TIME_T_MAX
        // sentinel this module represents as `None`).
        let abs = match now.checked_add(expires) {
            Some(v) if v < i64::MAX => Some(v),
            _ => None,
        };

        // Update an existing exact entry, otherwise create a fresh one.
        if let Some(idx) = self.find_and_prune(hostname, false, now) {
            self.entries[idx].expires = abs;
            self.entries[idx].include_subdomains = subdomains;
        } else {
            self.create(hostname, subdomains, abs);
        }
        Ok(())
    }
}

