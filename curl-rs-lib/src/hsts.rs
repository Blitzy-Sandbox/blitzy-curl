/// Status code returned by the HSTS read/write callbacks.
///
/// Mirrors the C `CURLSTScode` enum from `include/curl/curl.h`:
///
/// ```c
/// typedef enum { CURLSTS_OK, CURLSTS_DONE, CURLSTS_FAIL } CURLSTScode;
/// ```
///
/// The discriminants are pinned to the C integer values so the FFI trampoline
/// can convert with a plain cast.
#[repr(i32)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum HstsCode {
    /// `CURLSTS_OK` — the callback produced/accepted an entry; keep going.
    Ok = 0,
    /// `CURLSTS_DONE` — iteration is finished; stop without error.
    Done = 1,
    /// `CURLSTS_FAIL` — the callback failed; abort the operation.
    Fail = 2,
}

/// A single HSTS entry as exchanged with an application callback.
///
/// Mirrors `struct curl_hstsentry` from `include/curl/curl.h`:
///
/// ```c
/// struct curl_hstsentry {
///   char *name;
///   size_t namelen;
///   unsigned int includeSubDomains:1;
///   char expire[18]; /* YYYYMMDD HH:MM:SS [null-terminated] */
/// };
/// ```
///
/// The `expire` field uses curl's textual convention: an empty string on the
/// read side means "no expiry" (unlimited); on the write side an unlimited
/// entry is rendered as the [`UNLIMITED`] sentinel, otherwise as
/// `YYYYMMDD HH:MM:SS` in UTC.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct HstsEntry {
    /// The host name (without any leading `.`), as C's `name` / `namelen`.
    pub name: String,
    /// Whether the entry applies to sub-domains, as C's `includeSubDomains`.
    pub include_subdomains: bool,
    /// The textual expiry stamp, as C's `expire[18]` (see the type docs).
    pub expire: String,
}

// ---------------------------------------------------------------------------
// StsEntry — the in-memory entry, mirroring `struct stsentry`
// ---------------------------------------------------------------------------

/// A single stored HSTS entry.
///
/// Mirrors curl's `struct stsentry`:
///
/// ```c
/// struct stsentry {
///   struct Curl_llist_node node;
///   curl_off_t expires;         /* the timestamp of this entry's expiry */
///   BIT(includeSubDomains);
///   char host[1];
/// };
/// ```
///
/// The C flexible-array `host` becomes an owned [`String`]; the intrusive
/// linked-list `node` is unnecessary because the [`Hsts`] store owns entries in
/// insertion order. The `curl_off_t expires` becomes an [`Option<i64>`] Unix
/// timestamp where [`None`] is curl's `TIME_T_MAX` "unlimited" sentinel.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StsEntry {
    /// Stored host, always without a leading or trailing dot.
    host: String,
    /// Whether the policy extends to sub-domains of [`host`](StsEntry::host).
    include_subdomains: bool,
    /// Expiry as a Unix timestamp (seconds, UTC). [`None`] means the entry
    /// never expires (curl's `TIME_T_MAX`); `Some(0)` is an already-expired
    /// entry, matching curl leaving `expires == 0` on an unparseable date.
    expires: Option<i64>,
}

impl StsEntry {
    /// The stored host name (never carries a leading or trailing dot).
    #[must_use]
    pub fn host(&self) -> &str {
        &self.host
    }

    /// Whether this policy extends to sub-domains of [`host`](StsEntry::host).
    #[must_use]
    pub fn include_subdomains(&self) -> bool {
        self.include_subdomains
    }

    /// The expiry timestamp, or [`None`] for an entry that never expires.
    #[must_use]
    pub fn expires(&self) -> Option<i64> {
        self.expires
    }

    /// Returns `true` when this entry is expired relative to `now` (a Unix
    /// timestamp). An unlimited entry ([`None`]) is never expired.
    ///
    /// Mirrors curl's `sts->expires <= now` test (with `TIME_T_MAX` — here
    /// [`None`] — never satisfying it).
    #[must_use]
    fn is_expired(&self, now: i64) -> bool {
        match self.expires {
            None => false,
            Some(ts) => ts <= now,
        }
    }
}

