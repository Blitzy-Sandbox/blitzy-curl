    #[test]
    fn parse_rejects_malformed_headers() {
        let mut h = Hsts::new();
        // Missing mandatory max-age.
        assert!(h.parse_at("example.com", "includeSubDomains", NOW).is_err());
        // Empty header.
        assert!(h.parse_at("example.com", "", NOW).is_err());
        // Duplicate max-age.
        assert!(h
            .parse_at("example.com", "max-age=1; max-age=2", NOW)
            .is_err());
        // Duplicate includeSubDomains.
        assert!(h
            .parse_at(
                "example.com",
                "max-age=1; includeSubDomains; includeSubDomains",
                NOW
            )
            .is_err());
        // max-age with no '='.
        assert!(h.parse_at("example.com", "max-age 5", NOW).is_err());
        // max-age with no number.
        assert!(h.parse_at("example.com", "max-age=", NOW).is_err());
        // No entry should have been created by any failed parse.
        assert_eq!(h.len(), 0);
    }

