/// Returns `true` for curl's `ISBLANK`: an ASCII space or horizontal tab.
fn is_blank(b: u8) -> bool {
    b == b' ' || b == b'\t'
}

/// Case-insensitive ASCII prefix test, equivalent to
/// `curl_strnequal(needle, haystack, needle.len())`.
fn eq_ci_prefix(haystack: &[u8], needle: &[u8]) -> bool {
    haystack.len() >= needle.len() && haystack[..needle.len()].eq_ignore_ascii_case(needle)
}

/// Result of [`parse_u_number`], mirroring the relevant `STRE_*` codes.
enum NumParse {
    /// A value was parsed successfully.
    Ok(i64),
    /// The value overflowed the supplied maximum (`STRE_OVERFLOW`).
    Overflow,
    /// The first byte was not a digit (`STRE_NO_NUM`).
    NoNum,
}

/// Parses an unsigned decimal number at `bytes[*pos..]`.
///
/// Faithful port of curl's `curlx_str_number` / `str_num_base(base = 10)` for
/// the `max >= base` path used here (`max == i64::MAX`):
///
/// * On success, advances `*pos` past the digits and returns [`NumParse::Ok`].
/// * On overflow past `max`, returns [`NumParse::Overflow`] and leaves `*pos`
///   **unchanged** — `str_num_base` only writes `*linep` on success, so the
///   caller's cursor stays at the number's start. Reproducing this exactly is
///   what makes a `max-age="<overflow>"` header correctly fail on its missing
///   closing quote, just as curl does.
/// * If the first byte is not a digit, returns [`NumParse::NoNum`] without
///   advancing.
fn parse_u_number(bytes: &[u8], pos: &mut usize, max: i64) -> NumParse {
    let start = *pos;
    if start >= bytes.len() || !bytes[start].is_ascii_digit() {
        return NumParse::NoNum;
    }
    let mut num: i64 = 0;
    let mut i = start;
    while i < bytes.len() && bytes[i].is_ascii_digit() {
        let n = i64::from(bytes[i] - b'0');
        // Overflow check identical to str_num_base's `num > (max - n) / base`.
        if num > (max - n) / 10 {
            return NumParse::Overflow;
        }
        num = num * 10 + n;
        i += 1;
    }
    *pos = i;
    NumParse::Ok(num)
}

