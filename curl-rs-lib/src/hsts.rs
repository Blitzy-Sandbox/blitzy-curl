/// Maximum accepted length of a single line in the on-disk cache file.
///
/// Mirrors `#define MAX_HSTS_LINE 4095`. Lines longer than this are rejected
/// by the loader exactly as curl rejects them.
pub const MAX_HSTS_LINE: usize = 4095;

/// Maximum accepted host-name length, in bytes.
///
/// Mirrors `#define MAX_HSTS_HOSTLEN 2048`. Both the file parser and
/// [`Hsts::is_hsts`] treat a longer host as a non-match.
pub const MAX_HSTS_HOSTLEN: usize = 2048;

/// Maximum accepted length of the quoted expiry field in the file, in bytes.
///
/// Mirrors `#define MAX_HSTS_DATELEN 256`.
pub const MAX_HSTS_DATELEN: usize = 256;

/// The sentinel string curl writes (and reads) for entries that never expire.
///
/// Mirrors `#define UNLIMITED "unlimited"`.
pub const UNLIMITED: &str = "unlimited";

/// Enable-HSTS bit for the `CURLOPT_HSTS_CTRL` bitmask.
///
/// Mirrors `#define CURLHSTS_ENABLE (1L << 0)` from `include/curl/curl.h`.
pub const CURLHSTS_ENABLE: u32 = 1 << 0;

/// Read-only-file bit for the `CURLOPT_HSTS_CTRL` bitmask.
///
/// Mirrors `#define CURLHSTS_READONLYFILE (1L << 1)`. When set, [`Hsts::save`]
/// leaves the backing file untouched.
pub const CURLHSTS_READONLYFILE: u32 = 1 << 1;

/// The two comment lines curl writes at the top of every saved cache file.
///
/// Reproduced verbatim (including the trailing newlines) so that a file this
/// module writes is byte-identical to one curl 8.x writes for the same set of
/// entries.
const FILE_HEADER: &str = "# Your HSTS cache. https://curl.se/docs/hsts.html\n\
                           # This file was generated by libcurl! Edit at your own risk.\n";

