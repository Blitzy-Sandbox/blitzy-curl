/// Returns the current wall-clock time as a Unix timestamp (seconds, UTC).
///
/// A pre-1970 clock (which cannot happen in practice) clamps to `0`.
fn system_now() -> i64 {
    match SystemTime::now().duration_since(UNIX_EPOCH) {
        Ok(d) => d.as_secs() as i64,
        Err(_) => 0,
    }
}

/// The "current time" used by the public entry points.
///
/// In debug and test builds this honors the `CURL_TIME` environment variable,
/// exactly mirroring curl's `hsts_debugtime()` which is compiled under
/// `#if defined(DEBUGBUILD) || defined(UNITTESTS)`. This lets the curl test
/// corpus (and this module's own tests) pin "now" for deterministic expiry
/// behavior. Release builds always use the real clock, matching curl's release
/// behavior.
#[cfg(any(test, debug_assertions))]
fn hsts_now() -> i64 {
    if let Ok(timestr) = std::env::var("CURL_TIME") {
        if let Ok(val) = timestr.trim().parse::<i64>() {
            return val;
        }
    }
    system_now()
}

/// The "current time" used by the public entry points (release builds).
#[cfg(not(any(test, debug_assertions)))]
fn hsts_now() -> i64 {
    system_now()
}

// ---------------------------------------------------------------------------
// Date helpers — chrono-backed, byte-for-byte with curl's gmtime formatting
// ---------------------------------------------------------------------------

/// Formats an expiry into the exact textual stamp curl writes.
///
/// [`None`] (unlimited) yields the [`UNLIMITED`] sentinel. `Some(ts)` yields
/// `YYYYMMDD HH:MM:SS` in UTC, reproducing curl's
/// `curl_msnprintf(…, "%d%02d%02d %02d:%02d:%02d", tm_year+1900, tm_mon+1, …)`:
/// the year is emitted with no zero-padding (`%d`) and the remaining fields are
/// two-digit zero-padded (`%02d`).
///
/// Returns [`Error::with_context`] with [`CurlCode::BadFunctionArgument`] if
/// the timestamp is outside the representable calendar range (curl's
/// `curlx_gmtime` failure), which cannot occur for real HSTS expiries.
fn format_expiry(expires: Option<i64>) -> Result<String> {
    match expires {
        None => Ok(UNLIMITED.to_string()),
        Some(ts) => {
            let dt: DateTime<Utc> = DateTime::<Utc>::from_timestamp(ts, 0).ok_or_else(|| {
                Error::with_context(
                    crate::error::CurlCode::BadFunctionArgument,
                    "HSTS expiry timestamp out of range",
                )
            })?;
            Ok(format!(
                "{}{:02}{:02} {:02}:{:02}:{:02}",
                dt.year(),
                dt.month(),
                dt.day(),
                dt.hour(),
                dt.minute(),
                dt.second()
            ))
        }
    }
}

/// Parses the `YYYYMMDD HH:MM:SS` stamp curl writes into a Unix timestamp.
///
/// This is the chrono-backed equivalent of the path curl's
/// `Curl_getdate_capped` takes for the fixed stamp its own writer emits (and
/// which the callback `expire` field is documented to use). The eight-digit
/// date is split as `year = [0..4]`, `month = [4..6]`, `day = [6..8]`, exactly
/// mirroring `parsedate.c`'s `val/10000`, `(val%10000)/100`, `val%100`
/// decomposition of a `YYYYMMDD` token. A missing time component defaults to
/// `00:00:00`, as curl's parser zeroes an absent time.
///
/// Returns [`None`] for any input that does not match the expected shape or
/// denotes an invalid calendar instant; callers treat that as curl does when
/// `getdate` fails — an `expires` of `0` (an already-expired entry).
fn parse_general_date(s: &str) -> Option<i64> {
    let s = s.trim();
    let (date_part, time_part) = match s.split_once(' ') {
        Some((d, t)) => (d, t.trim_start()),
        None => (s, ""),
    };

    // The date must be exactly eight ASCII digits: YYYYMMDD.
    if date_part.len() != 8 || !date_part.bytes().all(|b| b.is_ascii_digit()) {
        return None;
    }
    let year: i32 = date_part[0..4].parse().ok()?;
    let month: u32 = date_part[4..6].parse().ok()?;
    let day: u32 = date_part[6..8].parse().ok()?;

    // Time is HH:MM:SS; an absent field defaults to zero (as curl does).
    let (hour, minute, second) = parse_hms(time_part)?;

    let date = NaiveDate::from_ymd_opt(year, month, day)?;
    let time = NaiveTime::from_hms_opt(hour, minute, second)?;
    Some(NaiveDateTime::new(date, time).and_utc().timestamp())
}

/// Parses an `HH:MM:SS` (or shorter, colon-separated) time.
///
/// Missing trailing components default to `0`, mirroring curl's
/// `if(-1 == secnum) secnum = minnum = hournum = 0;`. An empty string is a
/// valid `00:00:00`. Any non-numeric component fails the parse.
fn parse_hms(time_part: &str) -> Option<(u32, u32, u32)> {
    if time_part.is_empty() {
        return Some((0, 0, 0));
    }
    let mut it = time_part.split(':');
    let hour = parse_time_field(it.next())?;
    let minute = parse_time_field(it.next())?;
    let second = parse_time_field(it.next())?;
    // Reject trailing garbage such as "00:00:00:00".
    if it.next().is_some() {
        return None;
    }
    Some((hour, minute, second))
}

/// Parses one optional colon-separated time field; an absent field is `0`.
fn parse_time_field(field: Option<&str>) -> Option<u32> {
    match field {
        None => Some(0),
        Some(f) => f.parse::<u32>().ok(),
    }
}

/// Returns `true` when `host` is a numeric IP literal (IPv4 or IPv6).
///
/// Mirrors curl's `Curl_host_is_ipnum`, which RFC 6797 §8.3 uses to exclude
/// IP-address hosts from HSTS entirely ("explicit IP address identification of
/// all forms is excluded").
fn is_ip_address(host: &str) -> bool {
    host.parse::<std::net::Ipv4Addr>().is_ok() || host.parse::<std::net::Ipv6Addr>().is_ok()
}

// ---------------------------------------------------------------------------
// Core matching, insertion and removal — mirroring Curl_hsts / hsts_create
// ---------------------------------------------------------------------------

impl Hsts {
    /// Finds the best matching, non-expired entry for `host`.
    ///
    /// This is the read-only heart of curl's `Curl_hsts`. It:
    ///
    /// * returns [`None`] immediately if the query length is `0` or exceeds
    ///   [`MAX_HSTS_HOSTLEN`];
    /// * strips a single trailing `.` from the query name;
    /// * ignores expired entries (unlike `Curl_hsts` it does **not** remove
    ///   them here — removal happens in the `&mut` paths via
    ///   [`find_and_prune`](Hsts::find_and_prune) — because this borrows
    ///   `&self`);
    /// * returns an exact (ASCII case-insensitive) host match as soon as it is
    ///   seen; and
    /// * otherwise, when `subdomain` is set, returns the entry with the
    ///   *longest* `includeSubDomains` tail match, applying curl's
    ///   `ntail < hlen`, preceding-dot, and case-insensitive-tail rule.
    ///
    /// The returned value is an index into [`entries`](Hsts::entries).
    fn find(&self, host: &str, subdomain: bool, now: i64) -> Option<usize> {
        let bytes = host.as_bytes();
        let mut hlen = bytes.len();

        if hlen > MAX_HSTS_HOSTLEN || hlen == 0 {
            return None;
        }
        // Remove a single trailing dot from the query name.
        if bytes[hlen - 1] == b'.' {
            hlen -= 1;
        }
        if hlen == 0 {
            // The query was just "."; nothing can match.
            return None;
        }
        let query = &bytes[..hlen];

        let mut best: Option<usize> = None;
        let mut best_len = 0usize;

        for (idx, sts) in self.entries.iter().enumerate() {
            if sts.is_expired(now) {
                continue;
            }
            let ehost = sts.host.as_bytes();
            let ntail = ehost.len();

            if subdomain && sts.include_subdomains && ntail < hlen {
                let offs = hlen - ntail;
                // The byte before the tail must be a dot, the tail must match
                // case-insensitively, and we keep only the longest such tail.
                if query[offs - 1] == b'.'
                    && query[offs..].eq_ignore_ascii_case(ehost)
                    && ntail > best_len
                {
                    best = Some(idx);
                    best_len = ntail;
                }
            }

            // Exact match wins outright (curl returns it immediately).
            if hlen == ntail && query.eq_ignore_ascii_case(ehost) {
                return Some(idx);
            }
        }

        best
    }

    /// Removes every expired entry relative to `now`.
    ///
    /// Preserves the relative order of the surviving entries, matching curl's
    /// in-place list removal (and keeping the saved-file byte order stable).
    fn prune_expired(&mut self, now: i64) {
        self.entries.retain(|e| !e.is_expired(now));
    }

    /// Prunes expired entries, then finds the best match — the full `&mut`
    /// equivalent of `Curl_hsts` (which removes expired entries as it scans).
    ///
    /// Because expired entries never match, pruning first and then running the
    /// read-only [`find`](Hsts::find) yields exactly the same match `Curl_hsts`
    /// would return from its single removing pass.
    fn find_and_prune(&mut self, host: &str, subdomain: bool, now: i64) -> Option<usize> {
        self.prune_expired(now);
        self.find(host, subdomain, now)
    }

    /// Appends a new entry (curl's `hsts_create`).
    ///
    /// A single trailing dot is stripped from `host`; if nothing remains the
    /// entry is silently dropped (`if(hlen)` in the C source). No leading-dot
    /// handling happens here — callers strip a leading `.` and set `subdomains`
    /// before calling, exactly as `hsts_add` does. Entries are appended at the
    /// tail so insertion order (and therefore saved-file order) is preserved.
    fn create(&mut self, host: &str, subdomains: bool, expires: Option<i64>) {
        let bytes = host.as_bytes();
        let mut hlen = host.len();
        if hlen > 0 && bytes[hlen - 1] == b'.' {
            hlen -= 1;
        }
        if hlen > 0 {
            // `host[..hlen]` is a valid boundary: we only trimmed a trailing
            // ASCII '.', and the input is already valid UTF-8.
            self.entries.push(StsEntry {
                host: host[..hlen].to_string(),
                include_subdomains: subdomains,
                expires,
            });
        }
    }

    /// Removes the entry that exactly matches `host` (no sub-domain matching).
    ///
    /// Mirrors the `max-age=0` branch of `Curl_hsts_parse`, which looks the
    /// host up with `subdomain = FALSE` and removes it if present.
    fn remove_exact(&mut self, host: &str, now: i64) {
        if let Some(idx) = self.find_and_prune(host, false, now) {
            self.entries.remove(idx);
        }
    }

    /// Returns `true` when `host` is currently a known-HSTS host and must be
    /// upgraded from `http://` to `https://`.
    ///
    /// This is the public form of curl's `Curl_hsts(h, host, len, TRUE)` call
    /// (the sub-domain-aware lookup performed at `lib/url.c`). Expired entries
    /// are ignored; IP-address hosts simply never match any stored name.
    #[must_use]
    pub fn is_hsts(&self, host: &str) -> bool {
        self.is_hsts_at(host, hsts_now())
    }

    /// [`is_hsts`](Hsts::is_hsts) with an explicit "now", for deterministic
    /// testing and for callers that already hold a timestamp.
    #[must_use]
    fn is_hsts_at(&self, host: &str, now: i64) -> bool {
        self.find(host, true, now).is_some()
    }

    /// Returns the best matching, non-expired entry for `host`, if any.
    ///
    /// Sub-domain matching is enabled, matching the upgrade-decision lookup.
    /// This mirrors `Curl_hsts` returning the matched `struct stsentry`.
    #[must_use]
    pub fn lookup(&self, host: &str) -> Option<&StsEntry> {
        self.find(host, true, hsts_now())
            .map(|idx| &self.entries[idx])
    }
}

